//! Mux/Xum native chat.jsonl plus its sealed archive. Only completed edit receipts.
use crate::{native_history as n, trace_import as imp, Activity, Health, Stats};
use creditia_core::model::{FileGroup, PathMap, Src, Store};
use serde_json::Value;
use std::{
    collections::HashSet,
    path::{Path, PathBuf},
};

fn root() -> PathBuf {
    for key in ["CREDITIA_MUX_DIR", "XUM_ROOT", "MUX_ROOT"] {
        if let Some(p) = std::env::var_os(key) {
            return p.into();
        }
    }
    for name in [".xum", ".mux", ".cmux"] {
        let p = crate::home().join(name);
        if p.join("sessions").is_dir() {
            return p;
        }
    }
    crate::home().join(".xum")
}
fn paths() -> Vec<PathBuf> {
    let mut paths = n::files(&root().join("sessions"), |p| {
        matches!(
            p.file_name().and_then(|n| n.to_str()),
            Some("chat.jsonl" | "chat-archive.jsonl")
        )
    });
    for p in &mut paths {
        *p = p.parent().unwrap().into();
    }
    paths.sort();
    paths.dedup();
    paths
}
fn cwd(dir: &Path) -> String {
    let id = dir.file_name().and_then(|s| s.to_str()).unwrap_or("");
    let config = n::json(&root().join("config.json")).unwrap_or(Value::Null);
    for project in config["projects"].as_array().into_iter().flatten() {
        for workspace in project[1]["workspaces"].as_array().into_iter().flatten() {
            if workspace["id"] == id {
                return workspace["path"]
                    .as_str()
                    .filter(|p| !p.is_empty())
                    .unwrap_or(n::text(&project[0]))
                    .into();
            }
        }
    }
    String::new()
}
#[allow(clippy::too_many_arguments)]
fn receipt(
    g: &mut FileGroup,
    pm: &PathMap,
    cwd: &str,
    input: &Value,
    output: &Value,
    model: &str,
    id: &str,
    ts: i64,
) {
    let output = if output["type"] == "json" {
        &output["value"]
    } else {
        output
    };
    if output["success"] != true || output["diffTruncated"] == true {
        return;
    }
    let path = ["path", "file_path", "filePath"]
        .into_iter()
        .find_map(|k| input[k].as_str())
        .unwrap_or("");
    if path.is_empty() {
        return;
    }
    let diff = output["ui_only"]["file_edit"]["diff"]
        .as_str()
        .or_else(|| output["diff"].as_str())
        .unwrap_or("");
    // A diff is generated by the tool for this input path. Its header can be a display label.
    let added = crate::added_from_diff(diff);
    imp::push_scoped(g, pm, cwd, path, &added, Src::Mux, model, id, ts);
}
fn parse(rows: &[Value], pm: &PathMap, cwd: &str, id: &str) -> FileGroup {
    let mut g = FileGroup::default();
    let mut seen = HashSet::new();
    let latest: std::collections::HashMap<_, _> = rows
        .iter()
        .enumerate()
        .filter_map(|(i, r)| r["id"].as_str().filter(|s| !s.is_empty()).map(|s| (s, i)))
        .collect();
    let mut start = i64::MAX;
    let mut end = 0;
    let mut prompts = 0;
    for (i, row) in rows.iter().enumerate() {
        let mid = n::text(&row["id"]);
        if latest.get(mid).is_some_and(|last| *last != i) {
            continue;
        }
        if row["metadata"]["synthetic"] == true || (!mid.is_empty() && !seen.insert(mid)) {
            continue;
        }
        let ts = crate::any_ts(&row["metadata"]["timestamp"]).unwrap_or(0);
        if ts > 0 {
            start = start.min(ts);
            end = end.max(ts);
        }
        if row["role"] == "user" {
            prompts += 1;
        }
        if row["role"] != "assistant" {
            continue;
        }
        for part in row["parts"].as_array().into_iter().flatten() {
            if part["type"] != "dynamic-tool" || part["state"] != "output-available" {
                continue;
            }
            let model = n::text(&row["metadata"]["model"]);
            let edit = |name: &Value| {
                matches!(
                    n::text(name),
                    "file_edit_replace_string" | "file_edit_replace_lines" | "file_edit_insert"
                )
            };
            if edit(&part["toolName"]) {
                receipt(
                    &mut g,
                    pm,
                    cwd,
                    &part["input"],
                    &part["output"],
                    model,
                    id,
                    ts,
                );
            } else if part["toolName"] == "code_execution" {
                for call in part["output"]["toolCalls"].as_array().into_iter().flatten() {
                    if edit(&call["toolName"]) && call["error"].is_null() && call["ok"] != false {
                        receipt(
                            &mut g,
                            pm,
                            cwd,
                            &call["args"],
                            &call["result"],
                            model,
                            id,
                            ts,
                        );
                    }
                }
            }
        }
    }
    n::session(
        &mut g,
        pm,
        Src::Mux,
        id,
        cwd,
        if start == i64::MAX { 0 } else { start },
        end,
        prompts,
        0,
    );
    g
}
fn read(path: &Path, pm: &PathMap) -> Result<FileGroup, String> {
    let mut rows = vec![];
    for name in ["chat-archive.jsonl", "chat.jsonl"] {
        let p = path.join(name);
        if p.exists() {
            rows.extend(n::jsonl(&p)?);
        }
    }
    // Forked workspaces keep the parent transcript. Native usage metadata marks
    // the last copied timestamp; only later rows belong to the child workspace.
    if let Some(boundary) = n::json(&path.join("session-usage.json"))
        .ok()
        .and_then(|v| v["forkedAt"].as_i64())
    {
        rows.retain(|r| {
            r["metadata"]["timestamp"]
                .as_i64()
                .is_some_and(|t| t > boundary)
        });
    }
    Ok(parse(
        &rows,
        pm,
        &cwd(path),
        path.file_name().and_then(|s| s.to_str()).unwrap_or(""),
    ))
}
pub fn scan(store: &mut Store, pm: &PathMap, st: &mut Stats) {
    n::scan(Src::Mux, store, pm, st, paths(), read);
}
pub fn discover() -> Vec<Activity> {
    paths()
        .into_iter()
        .filter_map(|p| {
            let cwd = cwd(&p);
            (!cwd.is_empty()).then(|| imp::activity(Src::Mux, cwd, None, 0))
        })
        .collect()
}
pub fn doctor() -> Health {
    imp::health(Src::Mux, &root(), "native active + archived chat JSONL", paths().len(), "Completed file_edit receipts, including nested code_execution; incomplete or truncated diffs are excluded.", false)
}
#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;
    #[test]
    fn archive_duplicate_failure_and_nested_result() {
        let r = json!({"id":"m","role":"assistant","metadata":{"model":"actual-model"},"parts":[{"type":"dynamic-tool","state":"output-available","toolName":"file_edit_insert","input":{"path":"src/main.rs"},"output":{"success":true,"diff":"@@ -0,0 +1 @@\n+fn actual() {}\n"}}]});
        assert_eq!(
            parse(&[r.clone(), r.clone()], &n::project(), "/demo", "s")
                .evs
                .len(),
            1
        );
        let mut failed = r.clone();
        failed["parts"][0]["output"]["success"] = json!(false);
        assert!(parse(&[failed], &n::project(), "/demo", "s").evs.is_empty());
        let nested = json!({"role":"assistant","parts":[{"type":"dynamic-tool","state":"output-available","toolName":"code_execution","output":{"toolCalls":[{"toolName":"file_edit_insert","args":r["parts"][0]["input"],"result":r["parts"][0]["output"]}]}}]});
        assert_eq!(parse(&[nested], &n::project(), "/demo", "s").evs.len(), 1);
    }
}
