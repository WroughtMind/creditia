import { Scene } from './svg.ts';
import type { Style } from './style.ts';
import { materialEnter } from './material-motion.ts';
import { scrollLayerTimings, type ScrollMotion } from './scroll-motion.ts';

/** Native and web requests sample one SVG at a time. Reuse the existing reel's
 * declared content groups; no layout or full-reel rasterization is required. */
export function scrollFrameContent(svg: string, width: number, height: number, motion: ScrollMotion, progress: number, style: Style): string {
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  if (!motion.material || progress >= 1) return inner;
  const scene = new Scene(width, height);
  const seconds = Math.max(0, progress) * motion.secs;
  const replacements = new Map<string, string>();
  for (const layer of scrollLayerTimings(motion)) {
    const p = Math.max(0, Math.min(1, (seconds - layer.start!) / layer.duration!));
    if (p >= 1) continue;
    if (!layer.paint || !inner.includes(layer.paint)) throw new Error('Declared scroll content is missing from its artwork');
    // Work on the complete role/name/line. Data values are never printed as a
    // changing counter, and the scroll clock is shared with atlas exports.
    const captured = scene.capturePaint(() => materialEnter(scene, style, p, layer, () => scene.add(layer.paint), 'content'));
    replacements.set(layer.paint, captured);
  }
  // Definitions generated by materialEnter precede the original document.
  // Keep original paint order, including borders between content groups.
  const generated = scene.toString();
  const definitions = /<defs>[\s\S]*?<\/defs>/.exec(generated)?.[0] ?? '';
  let content = inner;
  for (const [paint, animated] of replacements) content = content.replace(paint, () => animated);
  return definitions + content;
}
